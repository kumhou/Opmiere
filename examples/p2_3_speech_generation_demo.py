"""P2.3 proof: local AI speech generation (Qwen3-TTS) through the real MCP
path, end to end - both modes:
  1. preset voice -> placed on an audio track alongside a video track,
     exported together (a real "video with narration" scenario).
  2. voice cloning -> a synthetic reference clip (generated by mode 1's
     model, NOT anyone's real voice) is cloned to prove the mechanism.
     To clone JH's actual voice, point reference_audio at a real 1-10s
     recording of him and reference_text at its transcript instead.

Requires OPMIERE_COMFYUI_INPUT_DIR set so voice cloning can upload its
reference clip into ComfyUI's own input/ folder.

Run:  python examples/p2_3_speech_generation_demo.py
"""

from __future__ import annotations

import asyncio
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

WORKDIR = Path(__file__).resolve().parent / "_p2_3_run"
FPS = 30


def show(label: str, result) -> dict | None:
    print(f"\n--- {label} ---")
    print("isError:", result.isError)
    parsed = None
    for block in result.content:
        text = getattr(block, "text", None)
        print("content:", text if text is not None else block)
        if text is not None and parsed is None:
            try:
                parsed = json.loads(text)
            except json.JSONDecodeError:
                parsed = text
    return parsed


async def poll_until_done(session, job_id: str, label: str, timeout_s: float = 180) -> dict:
    t0 = time.time()
    while True:
        status = show(f"job_status ({label})", await session.call_tool("job_status", {"job_id": job_id}))
        if status["status"] in ("done", "error"):
            return status
        if time.time() - t0 > timeout_s:
            raise TimeoutError(f"{label} generation did not finish in time")
        await asyncio.sleep(2)


def make_video_clip(path: Path) -> None:
    subprocess.run(
        ["ffmpeg", "-y", "-f", "lavfi", "-i", f"testsrc2=size=640x360:rate={FPS}:duration=6",
         "-c:v", "libx264", "-pix_fmt", "yuv420p", str(path)],
        capture_output=True, text=True, check=True,
    )


async def main() -> None:
    if WORKDIR.exists():
        shutil.rmtree(WORKDIR)
    WORKDIR.mkdir(parents=True)

    src_video = WORKDIR / "bg.mp4"
    make_video_clip(src_video)

    env = os.environ.copy()
    env.setdefault("OPMIERE_COMFYUI_INPUT_DIR", "G:/Development/ComfyUI/input")
    params = StdioServerParameters(command=sys.executable, args=["-m", "opmiere.mcp_server"], env=env)

    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            init = await session.initialize()
            print("Connected to MCP server:", init.serverInfo.name, init.serverInfo.version)

            show("create_project", await session.call_tool(
                "create_project",
                {"bundle_path": str(WORKDIR / "demo.opm"), "fps": FPS, "width": 640, "height": 360},
            ))

            media = show("import_media (background video)", await session.call_tool(
                "import_media", {"src_path": str(src_video), "kind": "video"}))
            video_track = show("add_track (video)", await session.call_tool("add_track", {"kind": "video"}))
            show("add_clip (background)", await session.call_tool(
                "add_clip",
                {"track_id": video_track["id"], "media_id": media["id"], "start": 0, "src_in": 0, "src_out": 180},
            ))

            # --- Mode 1: preset voice narration ---
            gen1 = await session.call_tool("generate", {
                "kind": "speech", "prompt": "Welcome to Opmiere, an agent native video editor.",
                "params": {"speaker": "Vivian", "language": "English"},
            })
            job1 = gen1.content[0].text
            print("\nspeech (preset) job_id:", job1)
            status1 = await poll_until_done(session, job1, "preset voice")
            if status1["status"] == "error":
                raise RuntimeError(f"preset voice generation failed: {status1['error']}")

            audio_track = show("add_track (audio)", await session.call_tool("add_track", {"kind": "audio"}))
            # duration_frames omitted on purpose: TTS output length isn't
            # known ahead of generation, so use the clip's real duration.
            show("place_generated (narration)", await session.call_tool(
                "place_generated",
                {"job_id": job1, "track_id": audio_track["id"], "start": 0},
            ))

            show("export (video + narration)", await session.call_tool(
                "export", {"output_path": str(WORKDIR / "output_with_narration.mp4")}
            ))

            # --- Mode 2: voice cloning (synthetic reference, not a real person) ---
            gen_ref = await session.call_tool("generate", {
                "kind": "speech", "prompt": "This is a synthetic reference voice, not a real person.",
                "params": {"speaker": "Dylan", "language": "English"},
            })
            ref_job = gen_ref.content[0].text
            ref_status = await poll_until_done(session, ref_job, "synthetic reference")
            if ref_status["status"] == "error":
                raise RuntimeError(f"reference generation failed: {ref_status['error']}")
            ref_path = ref_status["result_path"]

            gen_clone = await session.call_tool("generate", {
                "kind": "speech",
                "prompt": "This sentence proves the voice cloning mechanism works end to end through MCP.",
                "params": {
                    "reference_audio": ref_path,
                    "reference_text": "This is a synthetic reference voice, not a real person.",
                },
            })
            clone_job = gen_clone.content[0].text
            print("\nspeech (clone) job_id:", clone_job)
            clone_status = await poll_until_done(session, clone_job, "voice clone")
            if clone_status["status"] == "error":
                raise RuntimeError(f"voice clone generation failed: {clone_status['error']}")
            print("\nVoice clone result_path:", clone_status["result_path"])


if __name__ == "__main__":
    asyncio.run(main())
